enum L10n {

    static func string(for key: L10nKey, language: AppLanguage) -> String {
        switch language {
        case .en: return l10nEn[key] ?? "\(key)"
        case .zh: return l10nZh[key] ?? l10nEn[key] ?? "\(key)"
        case .ar: return l10nAr[key] ?? l10nEn[key] ?? "\(key)"
        case .es: return l10nEs[key] ?? l10nEn[key] ?? "\(key)"
        case .fr: return l10nFr[key] ?? l10nEn[key] ?? "\(key)"
        case .id: return l10nIndonesian[key] ?? l10nEn[key] ?? "\(key)"
        case .th: return l10nTh[key] ?? l10nEn[key] ?? "\(key)"
        }
    }
}
